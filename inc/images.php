/**
 * Convert every uploaded raster image to an optimized WebP before WordPress
 * creates the attachment (covers media library, REST API and sideloads).
 *
 * @param array $upload Upload data (file, url, type).
 * @return array
 */
function testro_convert_upload_to_webp( $upload ) {
	if ( ! empty( $upload['error'] ) || empty( $upload['file'] ) || empty( $upload['type'] ) ) {
		return $upload;
	}

	$file = $upload['file'];
	if ( ! testro_webp_is_convertible( $file, $upload['type'] ) ) {
		return $upload;
	}

	$is_webp = 'image/webp' === wp_get_image_mime( $file );
	if ( $is_webp && testro_webp_file_ok( $file ) ) {
		$dims = wp_getimagesize( $file );
		if ( $dims && max( $dims[0], $dims[1] ) <= TESTRO_WEBP_MAX_EDGE ) {
			return $upload;
		}
	}

	$dir = dirname( $file );
	if ( $is_webp ) {
		$dest = $file;
	} else {
		// wp_unique_filename() already reserved the .webp name for this upload (jpeg/png/gif map to webp).
		$name = pathinfo( $file, PATHINFO_FILENAME ) . '.webp';
		$dest = file_exists( $dir . '/' . $name ) ? $dir . '/' . wp_unique_filename( $dir, $name ) : $dir . '/' . $name;
	}

	$result = testro_webp_encode( $file, $dest );
	if ( is_wp_error( $result ) ) {
		error_log( 'TestRo WebP upload: ' . $result->get_error_message() ); // phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_error_log
		return $upload;
	}

	if ( $dest !== $file ) {
		wp_delete_file( $file );
	}

	$upload['file'] = $dest;
	$upload['type'] = 'image/webp';
	if ( ! empty( $upload['url'] ) ) {
		$upload['url'] = trailingslashit( dirname( $upload['url'] ) ) . wp_basename( $dest );
	}

	return $upload;
}
add_filter( 'wp_handle_upload', 'testro_convert_upload_to_webp' );

/**
 * Generate image sub-sizes as WebP.
 *
 * @param array $formats Mime map.
 * @return array
 */
function testro_image_editor_output_format( $formats ) {
	$formats['image/jpeg'] = 'image/webp';
	$formats['image/png']  = 'image/webp';
	$formats['image/gif']  = 'image/webp';
	return $formats;
}
add_filter( 'image_editor_output_format', 'testro_image_editor_output_format' );

/**
 * Default WebP quality for sub-sizes (oversized results are re-encoded afterwards).
 *
 * @param int    $quality Quality.
 * @param string $mime    Mime type.
 * @return int
 */
function testro_webp_editor_quality( $quality, $mime = '' ) {
	if ( 'image/webp' === $mime ) {
		return TESTRO_WEBP_QUALITY_MAX;
	}
	return $quality;
}
add_filter( 'wp_editor_set_quality', 'testro_webp_editor_quality', 10, 2 );

