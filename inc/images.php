/**
 * WebP counterpart of a theme image, relative to assets/.
 *
 * "images/home/hero.jpg" → "images/webp/home/hero.webp". Root-level images keep
 * the historical "images/webp/<name>.webp" location.
 *
 * @param string $path Path relative to assets/ (e.g. images/home/hero.jpg).
 * @return string Relative WebP path, or '' when the path is not convertible.
 */
function testro_webp_theme_relative( $path ) {
	$path = ltrim( (string) $path, '/' );
	if ( ! preg_match( '#^images/(.+)\.(png|jpe?g|gif)$#i', $path, $m ) ) {
		return '';
	}
	$first = strtolower( strtok( $m[1], '/' ) );
	if ( false !== strpos( $m[1], '/' ) && in_array( $first, testro_webp_theme_excluded_dirs(), true ) ) {
		return '';
	}
	return 'images/webp/' . $m[1] . '.webp';
}

/**
 * All convertible theme images, relative to assets/.
 *
 * @return string[]
 */
function testro_webp_theme_sources() {
	$base = TESTRO_DIR . '/assets/images';
	if ( ! is_dir( $base ) ) {
		return array();
	}

	$sources  = array();
	$iterator = new RecursiveIteratorIterator(
		new RecursiveCallbackFilterIterator(
			new RecursiveDirectoryIterator( $base, FilesystemIterator::SKIP_DOTS ),
			function ( $item ) use ( $base ) {
				if ( $item->isDir() ) {
					return dirname( $item->getPathname() ) !== $base
						|| ! in_array( strtolower( $item->getFilename() ), testro_webp_theme_excluded_dirs(), true );
				}
				return (bool) preg_match( '/\.(png|jpe?g|gif)$/i', $item->getFilename() );
			}
		)
	);
	foreach ( $iterator as $item ) {
		$sources[] = 'images/' . ltrim( str_replace( '\\', '/', substr( $item->getPathname(), strlen( $base ) ) ), '/' );
	}
	sort( $sources );
	return $sources;
}

/**
 * Generate missing or stale WebP versions of theme images.
 *
 * An existing WebP is reused when it is under the limit and was built from the
 * current source (tracked by source hash), so nothing is re-encoded needlessly.
 * Manifest entries are { hash, v } where v is the TESTRO_WEBP_VERSION that
 * encoded the file, or 'adopted' for a valid WebP that predates the manifest.
 *
 * @param bool  $force    Re-encode everything.
 * @param float $deadline microtime(true) after which to stop (0 = no limit).
 * @return array { processed: string[], skipped: string[], errors: string[], complete: bool }
 */
function testro_webp_optimize_theme_assets( $force = false, $deadline = 0 ) {
	$manifest = get_option( TESTRO_WEBP_ASSETS_OPTION, array() );
	$manifest = is_array( $manifest ) ? $manifest : array();
	$out      = array(
		'processed' => array(),
		'skipped'   => array(),
		'errors'    => array(),
		'complete'  => true,
	);
	$targets  = array();

	foreach ( testro_webp_theme_sources() as $rel ) {
		$webp_rel = testro_webp_theme_relative( $rel );
		$source   = TESTRO_DIR . '/assets/' . $rel;
		$target   = TESTRO_DIR . '/assets/' . $webp_rel;
		if ( '' === $webp_rel || ! testro_webp_is_convertible( $source ) ) {
			continue;
		}
		if ( isset( $targets[ $webp_rel ] ) ) {
			$out['errors'][] = sprintf( '%s skipped: %s already maps to %s', $rel, $targets[ $webp_rel ], $webp_rel );
			continue;
		}
		$targets[ $webp_rel ] = $rel;

		$hash  = md5_file( $source );
		$known = isset( $manifest[ $rel ]['hash'] ) ? $manifest[ $rel ] : null;
		$fresh = $known && $known['hash'] === $hash && in_array( $known['v'], array( TESTRO_WEBP_VERSION, 'adopted' ), true );
		if ( ! $force && testro_webp_file_ok( $target ) && ( null === $known || $fresh ) ) {
			if ( null === $known ) {
				$manifest[ $rel ] = array(
					'hash' => $hash,
					'v'    => 'adopted',
				);
			}
			$out['skipped'][] = $rel;
			continue;
		}

		if ( $deadline && microtime( true ) > $deadline ) {
			$out['complete'] = false;
			break;
		}

		$result = testro_webp_encode( $source, $target );
		if ( is_wp_error( $result ) ) {
			$out['errors'][] = $rel . ': ' . $result->get_error_message();
			continue;
		}
		$manifest[ $rel ]   = array(
			'hash' => $hash,
			'v'    => TESTRO_WEBP_VERSION,
		);
		$out['processed'][] = $rel;
	}

	update_option( TESTRO_WEBP_ASSETS_OPTION, $manifest, false );
	return $out;
}

/* -------------------------------------------------------------------------
 * Backfill (WP-Cron) and manual runs
 * ---------------------------------------------------------------------- */

/**
 * Signature that changes whenever the theme or this module changes.
 *
 * @return string
 */
function testro_webp_state_signature() {
	return TESTRO_VERSION . '|' . TESTRO_WEBP_VERSION;
}

/**
 * Process theme images and pending attachments.
 *
 * @param bool  $force    Re-encode even valid existing WebPs.
 * @param float $deadline microtime(true) after which to stop (0 = run to completion).
 * @return array { theme: array, attachments: array<int, string[]>, complete: bool, failed: bool }
 */
function testro_webp_optimize_all( $force = false, $deadline = 0 ) {
	$report = array(
		'theme'       => testro_webp_optimize_theme_assets( $force, $deadline ),
		'attachments' => array(),
		'complete'    => true,
		'failed'      => false,
	);
	$report['complete'] = $report['theme']['complete'];
	$report['failed']   = ! empty( $report['theme']['errors'] );

	if ( $force ) {
		delete_post_meta_by_key( TESTRO_WEBP_META_KEY );
	}

	$failed = array();
	while ( $report['complete'] ) {
		$ids = array_diff( testro_webp_pending_attachments( 20 ), $failed );
		if ( empty( $ids ) ) {
			break;
		}
		foreach ( $ids as $id ) {
			if ( $deadline && microtime( true ) > $deadline ) {
				$report['complete'] = false;
				break;
			}
			$result = testro_webp_optimize_attachment( $id, null, $force );
			if ( $result['changed'] ) {
				wp_update_attachment_metadata( $id, $result['metadata'] );
			}
			$report['attachments'][ $id ] = $result['errors'];
			if ( ! empty( $result['errors'] ) ) {
				$failed[]         = $id;
				$report['failed'] = true;
			}
		}
	}

	// Failures are not retried on every request; the backfill handler schedules a later retry.
	if ( $report['complete'] ) {
		update_option( TESTRO_WEBP_STATE_OPTION, testro_webp_state_signature(), false );
	}

	return $report;
}

/**
 * Cron handler: work for ~20 seconds, then reschedule if anything is left
 * (soon when out of time, in an hour when some image failed).
 */
function testro_webp_run_backfill() {
	$report = testro_webp_optimize_all( false, microtime( true ) + 20 );
	if ( ! $report['complete'] ) {
		wp_schedule_single_event( time() + 30, TESTRO_WEBP_BACKFILL_HOOK );
	} elseif ( $report['failed'] ) {
		wp_schedule_single_event( time() + HOUR_IN_SECONDS, TESTRO_WEBP_BACKFILL_HOOK );
	}
}
add_action( TESTRO_WEBP_BACKFILL_HOOK, 'testro_webp_run_backfill' );

/**
 * Queue a backfill after theme updates, and re-check daily for images added
 * outside the upload flow (FTP, deploys, imports).
 */
function testro_webp_maybe_schedule() {
	if ( get_option( TESTRO_WEBP_STATE_OPTION ) !== testro_webp_state_signature() ) {
		$next = wp_next_scheduled( TESTRO_WEBP_BACKFILL_HOOK );
		if ( $next && $next > time() + MINUTE_IN_SECONDS ) {
			wp_unschedule_event( $next, TESTRO_WEBP_BACKFILL_HOOK );
			$next = false;
		}
		if ( ! $next ) {
			wp_schedule_single_event( time(), TESTRO_WEBP_BACKFILL_HOOK );
		}
	}
	if ( ! wp_next_scheduled( 'testro_webp_daily' ) ) {
		wp_schedule_event( time() + HOUR_IN_SECONDS, 'daily', 'testro_webp_daily' );
	}
}
add_action( 'init', 'testro_webp_maybe_schedule' );
add_action( 'testro_webp_daily', 'testro_webp_run_backfill' );

/**
 * Stop the daily check when the theme is switched off.
 */
function testro_webp_unschedule() {
	wp_clear_scheduled_hook( 'testro_webp_daily' );
	wp_clear_scheduled_hook( TESTRO_WEBP_BACKFILL_HOOK );
}
add_action( 'switch_theme', 'testro_webp_unschedule' );

/**
 * Every served-image candidate with the WebP file that should be delivered.
 *
 * @return array[] { source, webp, bytes, ok }
 */
function testro_webp_audit() {
	$rows = array();
	$add  = function ( $source, $webp ) use ( &$rows ) {
		clearstatcache( true, $webp );
		$bytes  = is_file( $webp ) ? (int) filesize( $webp ) : 0;
		$rows[] = array(
			'source' => $source,
			'webp'   => $webp,
			'bytes'  => $bytes,
			'ok'     => testro_webp_fits( $bytes ) && 'image/webp' === wp_get_image_mime( $webp ),
		);
	};

	foreach ( testro_webp_theme_sources() as $rel ) {
		$source = TESTRO_DIR . '/assets/' . $rel;
		if ( testro_webp_is_convertible( $source ) ) {
			$add( $source, TESTRO_DIR . '/assets/' . testro_webp_theme_relative( $rel ) );
		}
	}

	$ids = get_posts(
		array(
			'post_type'      => 'attachment',
			'post_mime_type' => 'image',
			'post_status'    => 'inherit',
			'posts_per_page' => -1,
			'fields'         => 'ids',
		)
	);
	foreach ( $ids as $id ) {
		$file = get_attached_file( $id );
		$meta = wp_get_attachment_metadata( $id );
		if ( ! $file ) {
			continue;
		}
		$paths = array( $file );
		if ( ! empty( $meta['original_image'] ) ) {
			$paths[] = dirname( $file ) . '/' . $meta['original_image'];
		}
		foreach ( ! empty( $meta['sizes'] ) ? $meta['sizes'] : array() as $size ) {
			$paths[] = dirname( $file ) . '/' . $size['file'];
		}
		foreach ( array_unique( $paths ) as $path ) {
			if ( ! testro_webp_is_convertible( $path ) ) {
				continue;
			}
			$is_webp = 'image/webp' === wp_get_image_mime( $path );
			$add( $path, $is_webp ? $path : testro_webp_sidecar_path( $path ) );
		}
	}

	return $rows;
}

if ( defined( 'WP_CLI' ) && WP_CLI ) {
	/**
	 * `wp testro webp optimize [--force]` and `wp testro webp audit`.
	 *
	 * @param array $args       Positional args.
	 * @param array $assoc_args Flags.
	 */
	WP_CLI::add_command(
		'testro webp',
		function ( $args, $assoc_args ) {
			$command = isset( $args[0] ) ? $args[0] : 'optimize';
			if ( 'optimize' === $command ) {
				$report = testro_webp_optimize_all( ! empty( $assoc_args['force'] ) );
				WP_CLI::log( sprintf( 'Theme images: %d encoded, %d already optimized.', count( $report['theme']['processed'] ), count( $report['theme']['skipped'] ) ) );
				WP_CLI::log( sprintf( 'Attachments processed: %d.', count( $report['attachments'] ) ) );
				foreach ( $report['theme']['errors'] as $error ) {
					WP_CLI::warning( $error );
				}
			}
			$bad = 0;
			foreach ( testro_webp_audit() as $row ) {
				if ( ! $row['ok'] ) {
					++$bad;
					WP_CLI::warning( 'Not optimized: ' . $row['source'] );
				}
			}
			$bad ? WP_CLI::error( $bad . ' image(s) not optimized.' ) : WP_CLI::success( 'All images are WebP under the size limit.' );
		}
	);
}
