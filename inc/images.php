/**
 * Sidecar WebP path for a non-WebP file ("photo.jpg" → "photo.jpg.webp").
 *
 * @param string $file Absolute path.
 * @return string
 */
function testro_webp_sidecar_path( $file ) {
	return $file . '.webp';
}

/**
 * Make every file of an attachment satisfy the WebP rule.
 *
 * WebP files over the limit are re-encoded in place (metadata dimensions are
 * updated if they had to shrink); other raster files get a sidecar WebP.
 *
 * @param int        $attachment_id Attachment ID.
 * @param array|null $metadata      Attachment metadata (defaults to stored metadata).
 * @param bool       $force         Re-encode sidecars that already exist.
 * @return array { metadata: array, changed: bool, errors: string[] }
 */
function testro_webp_optimize_attachment( $attachment_id, $metadata = null, $force = false ) {
	$out  = array(
		'metadata' => is_array( $metadata ) ? $metadata : wp_get_attachment_metadata( $attachment_id ),
		'changed'  => false,
		'errors'   => array(),
	);
	$file = get_attached_file( $attachment_id );
	if ( ! $file || ! is_file( $file ) || ! is_array( $out['metadata'] ) ) {
		return $out;
	}

	$meta = &$out['metadata'];
	$dir  = trailingslashit( dirname( $file ) );

	// key => absolute path; key is 'full', 'original' or a size name.
	$files = array( 'full' => $file );
	if ( ! empty( $meta['original_image'] ) ) {
		$files['original'] = $dir . $meta['original_image'];
	}
	if ( ! empty( $meta['sizes'] ) && is_array( $meta['sizes'] ) ) {
		foreach ( $meta['sizes'] as $name => $size ) {
			if ( ! empty( $size['file'] ) ) {
				$files[ 'size:' . $name ] = $dir . $size['file'];
			}
		}
	}

	$done = array();
	foreach ( $files as $key => $path ) {
		if ( isset( $done[ $path ] ) || ! testro_webp_is_convertible( $path ) ) {
			continue;
		}
		$done[ $path ] = true;

		if ( 'image/webp' === wp_get_image_mime( $path ) ) {
			if ( testro_webp_file_ok( $path ) ) {
				continue;
			}
			$result = testro_webp_encode( $path, $path );
			if ( is_wp_error( $result ) ) {
				$out['errors'][] = $result->get_error_message();
				continue;
			}
			$out['changed'] = true;
			if ( 'full' === $key ) {
				$meta['width']    = $result['width'];
				$meta['height']   = $result['height'];
				$meta['filesize'] = $result['bytes'];
			} elseif ( 0 === strpos( $key, 'size:' ) ) {
				$name                              = substr( $key, 5 );
				$meta['sizes'][ $name ]['width']    = $result['width'];
				$meta['sizes'][ $name ]['height']   = $result['height'];
				$meta['sizes'][ $name ]['filesize'] = $result['bytes'];
			}
			continue;
		}

		$sidecar = testro_webp_sidecar_path( $path );
		if ( ! $force && testro_webp_file_ok( $sidecar ) && filemtime( $sidecar ) >= filemtime( $path ) ) {
			continue;
		}
		$result = testro_webp_encode( $path, $sidecar );
		if ( is_wp_error( $result ) ) {
			$out['errors'][] = $result->get_error_message();
		}
	}

	if ( empty( $out['errors'] ) ) {
		update_post_meta( $attachment_id, TESTRO_WEBP_META_KEY, TESTRO_WEBP_VERSION );
	}

	return $out;
}

/**
 * Optimize attachment files whenever WordPress (re)generates metadata.
 *
 * @param array $metadata      Attachment metadata.
 * @param int   $attachment_id Attachment ID.
 * @return array
 */
function testro_optimize_attachment_metadata( $metadata, $attachment_id ) {
	if ( ! wp_attachment_is_image( $attachment_id ) ) {
		return $metadata;
	}
	$result = testro_webp_optimize_attachment( $attachment_id, $metadata );
	return $result['metadata'];
}
add_filter( 'wp_generate_attachment_metadata', 'testro_optimize_attachment_metadata', 20, 2 );

/**
 * Delete sidecar WebPs together with the files they belong to.
 *
 * @param string $file Path being deleted.
 * @return string
 */
function testro_webp_delete_sidecar( $file ) {
	if ( is_string( $file ) && ! preg_match( '/\.webp$/i', $file ) ) {
		$sidecar = testro_webp_sidecar_path( $file );
		if ( is_file( $sidecar ) ) {
			@unlink( $sidecar ); // phpcs:ignore WordPress.PHP.NoSilencedErrors.Discouraged
		}
	}
	return $file;
}
add_filter( 'wp_delete_file', 'testro_webp_delete_sidecar' );

/**
 * Image attachments that have not been processed by the current version.
 *
 * @param int $limit Max IDs.
 * @return int[]
 */
function testro_webp_pending_attachments( $limit = 20 ) {
	$query = new WP_Query(
		array(
			'post_type'              => 'attachment',
			'post_status'            => 'inherit',
			'post_mime_type'         => array( 'image/jpeg', 'image/png', 'image/gif', 'image/webp', 'image/bmp', 'image/avif', 'image/heic', 'image/tiff' ),
			'posts_per_page'         => $limit,
			'fields'                 => 'ids',
			'orderby'                => 'ID',
			'order'                  => 'ASC',
			'no_found_rows'          => true,
			'update_post_term_cache' => false,
			'meta_query'             => array( // phpcs:ignore WordPress.DB.SlowDBQuery.slow_db_query_meta_query
				'relation' => 'OR',
				array(
					'key'     => TESTRO_WEBP_META_KEY,
					'compare' => 'NOT EXISTS',
				),
				array(
					'key'     => TESTRO_WEBP_META_KEY,
					'value'   => TESTRO_WEBP_VERSION,
					'compare' => '!=',
				),
			),
		)
	);
	return array_map( 'intval', $query->posts );
}

