<?php
/**
 * Global WebP optimisation.
 *
 * Every raster image the site serves is WebP and strictly smaller than
 * TESTRO_WEBP_MAX_BYTES:
 *
 * - New media uploads are converted to WebP before WordPress stores them, and
 *   their sub-sizes are generated as WebP.
 * - Attachments whose files are not WebP (uploaded before this module, or
 *   imported without wp_handle_upload) get a "<file>.<ext>.webp" sidecar next
 *   to every file, so the original URLs keep working.
 * - Theme images under assets/images/ get a mirror under assets/images/webp/.
 * - A WP-Cron backfill processes anything still missing; the front end swaps
 *   URLs to the WebP versions (inc/image-delivery.php).
 *
 * Manual run: php bin/optimize-images.php [--force] (or `wp testro webp optimize`).
 *
 * @package TestRo
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

if ( ! defined( 'TESTRO_WEBP_MAX_BYTES' ) ) {
	// Files must be strictly smaller than this (100 KB, decimal, so it also holds for 100 KiB).
	define( 'TESTRO_WEBP_MAX_BYTES', 100000 );
}
if ( ! defined( 'TESTRO_WEBP_QUALITY_MAX' ) ) {
	define( 'TESTRO_WEBP_QUALITY_MAX', 82 );
}
if ( ! defined( 'TESTRO_WEBP_QUALITY_MIN' ) ) {
	// Below this, dimensions are reduced instead of quality.
	define( 'TESTRO_WEBP_QUALITY_MIN', 50 );
}
if ( ! defined( 'TESTRO_WEBP_MAX_EDGE' ) ) {
	// Same as WordPress' big_image_size_threshold default.
	define( 'TESTRO_WEBP_MAX_EDGE', 2560 );
}

// Bump to re-process every attachment and re-encode theme WebPs generated by an older version.
define( 'TESTRO_WEBP_VERSION', '4' );
define( 'TESTRO_WEBP_META_KEY', '_testro_webp' );
define( 'TESTRO_WEBP_ASSETS_OPTION', 'testro_webp_assets' );
define( 'TESTRO_WEBP_STATE_OPTION', 'testro_webp_state' );
define( 'TESTRO_WEBP_BACKFILL_HOOK', 'testro_webp_backfill' );

/* -------------------------------------------------------------------------
 * Encoder
 * ---------------------------------------------------------------------- */

/**
 * Whether a byte count satisfies the size rule.
 *
 * @param int $bytes File size.
 * @return bool
 */
function testro_webp_fits( $bytes ) {
	return $bytes > 0 && $bytes < TESTRO_WEBP_MAX_BYTES;
}

/**
 * Whether a file exists and satisfies the size rule.
 *
 * @param string $path Absolute path.
 * @return bool
 */
function testro_webp_file_ok( $path ) {
	clearstatcache( true, $path );
	return is_file( $path ) && testro_webp_fits( (int) filesize( $path ) );
}

/**
 * Whether a GIF file is animated.
 *
 * @param string $file Absolute path.
 * @return bool
 */
function testro_is_animated_gif( $file ) {
	if ( ! is_readable( $file ) ) {
		return false;
	}

	$fh = fopen( $file, 'rb' );
	if ( ! $fh ) {
		return false;
	}

	$count = 0;
	$chunk = '';
	while ( ! feof( $fh ) && $count < 2 ) {
		$chunk .= fread( $fh, 1024 * 100 );
		$count  = preg_match_all( '/\x00\x21\xF9\x04.{4}\x00(\x2C|\x21)/s', $chunk, $m );
		if ( strlen( $chunk ) > 1024 * 1024 ) {
			break;
		}
	}
	fclose( $fh );

	return $count > 1;
}

/**
 * Whether a file is a raster image that should be served as WebP.
 *
 * Animated GIFs are skipped (converting would drop the animation).
 *
 * @param string $file Absolute path.
 * @param string $mime Optional known mime type.
 * @return bool
 */
function testro_webp_is_convertible( $file, $mime = '' ) {
	if ( ! is_file( $file ) ) {
		return false;
	}

	$real = wp_get_image_mime( $file );
	$mime = $real ? $real : $mime;

	$raster = array( 'image/jpeg', 'image/png', 'image/gif', 'image/webp', 'image/bmp', 'image/avif', 'image/heic', 'image/heif', 'image/tiff' );
	if ( ! in_array( $mime, $raster, true ) ) {
		return false;
	}

	if ( 'image/gif' === $mime && testro_is_animated_gif( $file ) ) {
		return false;
	}

	if ( 'image/webp' === $mime ) {
		$info = wp_get_webp_info( $file );
		if ( 'animated-alpha' === $info['type'] && testro_webp_is_animated( $file ) ) {
			return false;
		}
	}

	return wp_image_editor_supports( array( 'mime_type' => $mime ) );
}

/**
 * Whether a WebP file contains an animation chunk.
 *
 * @param string $file Absolute path.
 * @return bool
 */
function testro_webp_is_animated( $file ) {
	$head = (string) file_get_contents( $file, false, null, 0, 64 ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents
	return false !== strpos( $head, 'ANIM' );
}

/**
 * Temp file path next to a destination (same filesystem, so rename() is atomic).
 *
 * @param string $dest Destination path.
 * @param string $ext  Extension without dot.
 * @return string
 */
function testro_webp_temp_path( $dest, $ext = 'webp' ) {
	return trailingslashit( dirname( $dest ) ) . '.testro-' . wp_generate_password( 8, false ) . '.' . $ext;
}

/**
 * Save the editor's current image as WebP at a given quality.
 *
 * @param WP_Image_Editor $editor  Editor.
 * @param int             $quality Quality 1-100.
 * @param string          $path    Output path (.webp).
 * @return int Bytes written, 0 on failure.
 */
function testro_webp_try_quality( $editor, $quality, $path ) {
	// Converting formats makes WP_Image_Editor reset quality through this filter, overriding set_quality().
	$pin = function () use ( $quality ) {
		return $quality;
	};
	add_filter( 'wp_editor_set_quality', $pin, PHP_INT_MAX );
	$editor->set_quality( $quality );
	$saved = $editor->save( $path, 'image/webp' );
	remove_filter( 'wp_editor_set_quality', $pin, PHP_INT_MAX );
	if ( is_wp_error( $saved ) ) {
		return 0;
	}
	clearstatcache( true, $path );
	return is_file( $path ) ? (int) filesize( $path ) : 0;
}

/**
 * Save the editor's current image as lossless WebP.
 *
 * WP_Image_Editor cannot request lossless output, so the frame is exported as
 * PNG and re-encoded with GD.
 *
 * @param WP_Image_Editor $editor Editor.
 * @param string          $path   Output path (.webp).
 * @return int Bytes written, 0 when unsupported or on failure.
 */
function testro_webp_try_lossless( $editor, $path ) {
	if ( ! defined( 'IMG_WEBP_LOSSLESS' ) || ! function_exists( 'imagewebp' ) || ! function_exists( 'imagecreatefrompng' ) ) {
		return 0;
	}

	$keep_png = function ( $formats ) {
		unset( $formats['image/png'] );
		return $formats;
	};
	add_filter( 'image_editor_output_format', $keep_png, PHP_INT_MAX );
	$saved = $editor->save( testro_webp_temp_path( $path, 'png' ), 'image/png' );
	remove_filter( 'image_editor_output_format', $keep_png, PHP_INT_MAX );
	if ( is_wp_error( $saved ) ) {
		return 0;
	}

	$image = imagecreatefrompng( $saved['path'] );
	@unlink( $saved['path'] ); // phpcs:ignore WordPress.PHP.NoSilencedErrors.Discouraged
	if ( ! $image ) {
		return 0;
	}
	imagepalettetotruecolor( $image );
	imagealphablending( $image, false );
	imagesavealpha( $image, true );
	if ( ! imagewebp( $image, $path, IMG_WEBP_LOSSLESS ) ) {
		return 0;
	}
	clearstatcache( true, $path );
	return is_file( $path ) ? (int) filesize( $path ) : 0;
}

/**
 * Encode an image as WebP strictly under TESTRO_WEBP_MAX_BYTES.
 *
 * Keeps the original dimensions (capped at TESTRO_WEBP_MAX_EDGE) and picks the
 * highest quality between QUALITY_MIN and QUALITY_MAX that fits. Only if even
 * QUALITY_MIN is too large are the dimensions reduced, by an estimate derived
 * from the overshoot, and the quality search repeated.
 *
 * PNG/GIF sources also try lossless WebP at each size and keep it when it is
 * no larger than the lossy result. $source and $dest may be the same file.
 *
 * @param string $source Absolute source path.
 * @param string $dest   Absolute destination .webp path.
 * @return array|\WP_Error { path, width, height, quality (int|'lossless'), bytes }
 */
function testro_webp_encode( $source, $dest ) {
	if ( ! function_exists( 'wp_get_image_editor' ) ) {
		return new WP_Error( 'testro_webp_no_editor', 'Image editor unavailable.' );
	}
	if ( ! wp_mkdir_p( dirname( $dest ) ) ) {
		return new WP_Error( 'testro_webp_mkdir', 'Unable to create ' . dirname( $dest ) );
	}

	$q_max    = (int) TESTRO_WEBP_QUALITY_MAX;
	$q_min    = (int) TESTRO_WEBP_QUALITY_MIN;
	$tmp      = testro_webp_temp_path( $dest );
	$best     = testro_webp_temp_path( $dest );
	$cleanup  = array( $tmp, $best );
	$input    = $source;
	$result   = null;

	// WordPress forces lossless output when the source is a lossless WebP; decode via PNG instead.
	if ( 'image/webp' === wp_get_image_mime( $source ) ) {
		$info = wp_get_webp_info( $source );
		if ( 'lossless' === $info['type'] ) {
			$png      = testro_webp_temp_path( $dest, 'png' );
			$keep_png = function ( $formats ) {
				unset( $formats['image/png'] );
				return $formats;
			};
			add_filter( 'image_editor_output_format', $keep_png, PHP_INT_MAX );
			$editor = wp_get_image_editor( $source );
			$saved  = is_wp_error( $editor ) ? $editor : $editor->save( $png, 'image/png' );
			remove_filter( 'image_editor_output_format', $keep_png, PHP_INT_MAX );
			if ( is_wp_error( $saved ) ) {
				return $saved;
			}
			$input     = $saved['path'];
			$cleanup[] = $input;
		}
	}

	$graphic = in_array( wp_get_image_mime( $input ), array( 'image/png', 'image/gif' ), true );
	$target  = 0;
	while ( null === $result ) {
		$editor = wp_get_image_editor( $input );
		if ( is_wp_error( $editor ) ) {
			$result = $editor;
			break;
		}
		$editor->maybe_exif_rotate();

		$size = $editor->get_size();
		$long = max( (int) $size['width'], (int) $size['height'] );
		if ( ! $target ) {
			$target = min( $long, (int) TESTRO_WEBP_MAX_EDGE );
		}
		if ( $target < $long ) {
			$resized = $editor->resize( $target, $target, false );
			if ( is_wp_error( $resized ) ) {
				$result = $resized;
				break;
			}
			$size = $editor->get_size();
		} elseif ( $editor instanceof WP_Image_Editor_GD && in_array( wp_get_image_mime( $input ), array( 'image/png', 'image/gif' ), true ) ) {
			// GD cannot encode palette images as WebP; a full-frame crop yields a truecolor copy.
			$editor->crop( 0, 0, (int) $size['width'], (int) $size['height'] );
		}

		$fit_q = 0;
		$bytes = testro_webp_try_quality( $editor, $q_max, $tmp );
		if ( ! $bytes ) {
			$result = new WP_Error( 'testro_webp_encode', 'WebP encoding failed for ' . $source );
			break;
		}

		if ( testro_webp_fits( $bytes ) ) {
			$fit_q = $q_max;
			copy( $tmp, $best );
		} else {
			$min_bytes = testro_webp_try_quality( $editor, $q_min, $tmp );
			if ( testro_webp_fits( $min_bytes ) ) {
				$fit_q = $q_min;
				copy( $tmp, $best );
				$hi = $q_max;
				while ( $hi - $fit_q > 2 ) {
					$mid = (int) floor( ( $fit_q + $hi ) / 2 );
					if ( testro_webp_fits( testro_webp_try_quality( $editor, $mid, $tmp ) ) ) {
						$fit_q = $mid;
						copy( $tmp, $best );
					} else {
						$hi = $mid;
					}
				}
			}
		}

		// Flat graphics are often smaller as lossless WebP; use it when it fits and is no larger.
		if ( $graphic ) {
			clearstatcache( true, $best );
			$lossy_bytes    = $fit_q ? (int) filesize( $best ) : 0;
			$lossless_bytes = testro_webp_try_lossless( $editor, $tmp );
			if ( testro_webp_fits( $lossless_bytes ) && ( ! $fit_q || $lossless_bytes <= $lossy_bytes ) ) {
				copy( $tmp, $best );
				$fit_q = 'lossless';
			}
		}

		if ( $fit_q ) {
			if ( ! rename( $best, $dest ) ) {
				$result = new WP_Error( 'testro_webp_rename', 'Unable to write ' . $dest );
				break;
			}
			clearstatcache( true, $dest );
			$result = array(
				'path'    => $dest,
				'width'   => (int) $size['width'],
				'height'  => (int) $size['height'],
				'quality' => $fit_q,
				'bytes'   => (int) filesize( $dest ),
			);
			break;
		}

		// Even minimum quality is too big: shrink by the estimated area ratio (with headroom).
		$current = max( (int) $size['width'], (int) $size['height'] );
		$ratio   = sqrt( ( TESTRO_WEBP_MAX_BYTES * 0.9 ) / max( 1, (int) $min_bytes ) );
		$ratio   = min( 0.92, max( 0.5, $ratio ) );
		$target  = (int) floor( $current * $ratio );
		if ( $target < 16 ) {
			$result = new WP_Error( 'testro_webp_limit', 'Unable to encode ' . $source . ' under the size limit.' );
		}
	}

	foreach ( $cleanup as $file ) {
		if ( is_file( $file ) ) {
			@unlink( $file ); // phpcs:ignore WordPress.PHP.NoSilencedErrors.Discouraged
		}
	}

	return $result;
}

